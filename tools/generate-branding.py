#!/usr/bin/env python3
"""Generate Android's colour vectors and background from docs/branding/icon.svg."""

from pathlib import Path
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android/app/src/main/res"
SVG = ET.parse(ROOT / "docs/branding/icon.svg").getroot()
ATTRIBUTES = {
    "d": "pathData",
    "fill": "fillColor",
    "stroke": "strokeColor",
    "stroke-width": "strokeWidth",
    "stroke-linecap": "strokeLineCap",
    "stroke-linejoin": "strokeLineJoin",
    "fill-rule": "fillType",
}
if SVG.get("viewBox") != "0 0 108 108":
    raise ValueError("Keep the SVG viewBox at 0 0 108 108 for Android's icon layers")
for node in SVG:
    tag = node.tag.rsplit("}", 1)[-1]
    if tag not in {"path", "title", "desc"}:
        raise ValueError(f"Flatten SVG elements to paths before generating: {tag}")
    if tag == "path" and set(node.attrib) - {"id", *ATTRIBUTES}:
        raise ValueError("Flatten transforms/styles into the path data and colour attributes")
PATHS = [node for node in SVG if node.tag.rsplit("}", 1)[-1] == "path"]
if not PATHS:
    raise ValueError("The icon contains no paths")
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
NOTICE = "<!-- Generated by tools/generate-branding.py; edit docs/branding/icon.svg. -->\n"


def vector(paths, adaptive=False):
    lines = [
        HEADER + NOTICE,
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp" android:height="108dp"',
        '    android:viewportWidth="108" android:viewportHeight="108">',
    ]
    if adaptive:
        # Keep the twig aerials inside the central safe zone of circular masks.
        lines.append('    <group android:scaleX="0.8" android:scaleY="0.8" android:pivotX="54" android:pivotY="54">')
    for node in paths:
        attributes = []
        for source, target in ATTRIBUTES.items():
            value = node.get(source)
            if value is not None:
                if value == "none":
                    value = "#00000000"
                elif source == "fill-rule" and value == "evenodd":
                    value = "evenOdd"
                attributes.append(f"android:{target}={quoteattr(value)}")
        indent = "        " if adaptive else "    "
        lines.append(indent + "<path " + " ".join(attributes) + " />")
    if adaptive:
        lines.append("    </group>")
    return "\n".join(lines) + "\n</vector>\n"


if __name__ == "__main__":
    (RES / "drawable/ic_anime_levisione.xml").write_text(vector(PATHS), encoding="utf-8")
    foreground = [path for path in PATHS if path.get("id") != "background"]
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector(foreground, adaptive=True), encoding="utf-8")
    background = next(path.get("fill") for path in PATHS if path.get("id") == "background")
    (RES / "values/colors.xml").write_text(
        HEADER + NOTICE + '<resources>\n'
        f'    <color name="launcher_background">{background}</color>\n'
        '</resources>\n',
        encoding="utf-8",
    )
